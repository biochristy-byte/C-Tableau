"""Builds dev/fixtures.js (mock Tableau data) from data/life-expectancy-sample.csv plus a few
synthetic sets for edge cases. Seeded, so the file is identical every run."""
import csv, json, pathlib, random
root = pathlib.Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(root / 'data' / 'life-expectancy-sample.csv', encoding='utf-8')))
V = 'Life expectancy (years)'
fx = {}
fx['life'] = {'columns': ['Country', 'Year', V], 'rows': [[r['Country'], r['Year'], float(r[V])] for r in rows]}
last = [r for r in rows if r['Year'] == '2023']
fx['bars'] = {'columns': ['Country', V, 'Note'], 'rows': [[r['Country'], float(r[V]), 'born %s' % r['Year']] for r in last]}
rnd = random.Random(11)
names = ['Antigua and Barbuda', 'Bosnia and Herzegovina', 'Central African Republic', 'Democratic Republic of the Congo', 'Saint Vincent and the Grenadines', 'Trinidad and Tobago',
         'United Arab Emirates', 'Papua New Guinea', 'Sao Tome and Principe', 'Equatorial Guinea', 'Dominican Republic', 'North Macedonia']
fx['long'] = {'columns': ['Place', 'Score'], 'rows': [[n, round(rnd.uniform(20, 95), 1)] for n in names]}
fx['negative'] = {'columns': ['Quarter', 'Change', 'Region'], 'rows': [[q, c, r] for q, c, r in
                  [('Q1', 4.2, 'North'), ('Q2', -3.1, 'North'), ('Q3', 6.8, 'North'), ('Q4', -1.4, 'North'), ('Q1', -2.0, 'South'), ('Q2', 1.5, 'South'), ('Q3', -5.2, 'South'), ('Q4', 3.3, 'South')]]}
fx['one'] = {'columns': ['Thing', 'Amount'], 'rows': [['Only', 42]]}
fx['empty'] = {'columns': ['Thing', 'Amount'], 'rows': []}
open(root / 'dev' / 'fixtures.js', 'w', encoding='utf-8').write('/* generated by tools/make_fixtures.py, do not edit */\nwindow.SB_FIXTURES = ' + json.dumps(fx, separators=(',', ':')) + ';\n')
print({k: len(v['rows']) for k, v in fx.items()})
